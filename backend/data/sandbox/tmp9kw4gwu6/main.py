def add_two_numbers(a: float, b: float) -> float:
    """
    Adds two numbers a and b.

    Parameters:
        a (float): The first number.
        b (float): The second number.

    Returns:
        float: The sum of the two numbers.
    """
    return a + b

# Example usage
result = add_two_numbers(3.5, 2.7)
print(result)  # Output: 6.2